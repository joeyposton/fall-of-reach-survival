"""Generate C# from the design sheets: one record per row.

Writes Sheets.g.cs into the converter and the Unity game, so both read the
same rows. Run preflight.py first; this refuses to generate if it fails.
"""
import json
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parent
OUTPUTS = [
    ROOT / "converter" / "Generated" / "Sheets.g.cs",
    ROOT / "game" / "Assets" / "ReachSurvival" / "Generated" / "Sheets.g.cs",
]

if subprocess.run([sys.executable, str(HERE / "preflight.py")], capture_output=True).returncode != 0 and "--force" not in sys.argv:
    print("preflight has open items; run preflight.py (or pass --force while building early systems)")
    if "--allow-open" not in sys.argv:
        sys.exit(1)


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", s) if p)


def cs_type(values):
    vals = [v for v in values if v is not None]
    if vals and all(isinstance(v, bool) for v in vals):
        return "bool"
    if vals and all(isinstance(v, int) and not isinstance(v, bool) for v in vals):
        return "int"
    if vals and all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in vals):
        return "float"
    return "string"


def cs_value(v, t):
    if t == "bool":
        return "true" if v else "false"
    if t == "int":
        return str(v)
    if t == "float":
        return f"{float(v)}f"
    return json.dumps("" if v is None else str(v))


def tables(sheet):
    if "rows" in sheet:
        yield sheet["sheet"], sheet["columns"], sheet["rows"]
    for key, val in sheet.items():
        if isinstance(val, dict) and "rows" in val:
            yield key, val["columns"], val["rows"]


out = ["// <auto-generated> from sheets/*.json by sheets/gen.py. Edit the sheets, not this file. </auto-generated>",
       "namespace ReachSurvival.Sheets", "{"]
for path in sorted(HERE.glob("*.json")):
    sheet = json.loads(path.read_text())
    for table, cols, rows in tables(sheet):
        rec = pascal(table) + "Row"
        types = {c: cs_type([r.get(c) for r in rows]) for c in cols}
        fields = ", ".join(f"{types[c]} {pascal(c)}" for c in cols)
        out.append(f"    public sealed record {rec}({fields});")
        out.append(f"    public static partial class {pascal(table)}")
        out.append("    {")
        for r in rows:
            args = ", ".join(cs_value(r.get(c), types[c]) for c in cols)
            out.append(f"        public static readonly {rec} {pascal(r['id'])} = new({args});")
        out.append(f"        public static readonly {rec}[] All = {{ {', '.join(pascal(r['id']) for r in rows)} }};")
        out.append("    }")
out.append("}")
text = "\n".join(out) + "\n"
for o in OUTPUTS:
    o.parent.mkdir(parents=True, exist_ok=True)
    o.write_text(text)
    print("wrote", o)
